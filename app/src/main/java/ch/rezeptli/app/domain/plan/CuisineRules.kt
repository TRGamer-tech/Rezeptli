/**
 * Ordnet ein Rezept einer Kueche zu - aus dem Titel und den Schlagworten der Quelle.
 *
 * Die meisten Rezepte gehoeren zu keiner Kueche, die sich am Namen erkennen liesse; ein
 * Kartoffelgratin ist einfach ein Kartoffelgratin. Solche Rezepte bleiben ohne Zuordnung
 * und werden von einer Kuechen-Vorliebe weder bevorzugt noch zurueckgestellt.
 *
 * Verglichen wird mit ganzen Woertern. Zusammengesetzte Namen ("Poulet-Curry",
 * "Gemuesecurry") zaehlen ueber die Wortendung mit.
 */
internal object CuisineRules {
    fun of(title: List<String>, tags: Set<String>): Set<Cuisine> {
        val words = title.toSet()
        val phrase = title.joinToString(" ")
        return buildSet {
            RULES.forEach { rule ->
                val hit = tags.any { it in rule.tags } ||
                    words.any { word -> word in rule.words || rule.endings.any { word.endsWith(it) } } ||
                    rule.phrases.any { phrase.contains(it) }
                if (hit) add(rule.cuisine)
            }
        }
    }

